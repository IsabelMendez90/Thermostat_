def estimate_energy_from_runtime(runtime_hours: float, system_type: str = "central_ac") -> float:
    """
    Convert runtime hours to energy consumption (kWh).

    Based on typical HVAC system power consumption:
    - Central AC: 3.5 kW (EIA 2020)
    - Heat pump (cooling): 3.0 kW
    - Heat pump (heating): 3.5 kW
    - Gas furnace fan: 0.6 kW (fan only, gas not counted)

    Sources:
    - EIA 2020 Residential Energy Consumption Survey
    - DOE Building America Program data
    """
    # Power consumption in kW by system type
    POWER_CONSUMPTION_KW = {
        "central_ac": 3.5,  # Typical central AC unit
        "heat_pump_cool": 3.0,  # Heat pump in cooling mode
        "heat_pump_heat": 3.5,  # Heat pump in heating mode
        "gas_furnace_fan": 0.6,  # Gas furnace fan only
        "average": 3.2,  # Average across common systems
    }

    power_kw = POWER_CONSUMPTION_KW.get(system_type, POWER_CONSUMPTION_KW["average"])
    return runtime_hours * power_kw


