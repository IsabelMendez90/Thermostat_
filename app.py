    clear = st.button("Clear chat", use_container_width=False)

    if clear:
        st.session_state.assistant_messages = []
        st.session_state.pending_action = None
        st.session_state.pending_explainer = ""
        st.session_state.assistant_input_value = ""
        st.rerun()

