def compute_annual_runtime_with_historical_weather(
    schedules: Dict[str, Dict],
    tin_model: Any,
    runtime_predictor: Any,
    lat: float,
    lon: float,
    indoor_seed: float = 72.0,
    building_age: Optional[int] = None,
    building_type: Optional[str] = None,
    floor_area: Optional[float] = None,
    climate_code: str = "",
    hvac_mode: str = "Auto",
    year: int = 2023,
    schedule_priorities: Optional[Dict[str, int]] = None,
) -> Tuple[Optional[pd.DataFrame], Dict[str, Any]]:
    """
    Compute runtime predictions for a full year using actual historical weather data.

    This provides accurate monthly energy estimates instead of extrapolating from 7-day forecasts.

    Returns:
        - hourly_predictions: DataFrame with hourly runtime predictions for the full year
        - monthly_summary: Dict with monthly breakdown of energy usage
    """
    # Load full year weather data
    weather_df, location_id, distance_km = load_full_year_outdoor_temps(lat, lon, year)

    if weather_df is None or weather_df.empty:
        return None, {"error": f"Could not load weather data for year {year}", "location_id": location_id}

    if tin_model is None:
        return None, {"error": "Indoor temperature model not available"}

    # Process in monthly chunks to avoid memory issues
    weather_df["month"] = weather_df["time"].dt.month
    weather_df["hour"] = weather_df["time"].dt.hour
    weather_df["day_of_week"] = (weather_df["time"].dt.dayofweek + 1) % 7 + 1  # 1=Mon, 7=Sun
    weather_df["date"] = weather_df["time"].dt.date

    all_predictions = []
    monthly_summary = {
        "location_id": location_id,
        "distance_km": distance_km,
        "year": year,
        "months": {},
    }

    for month in range(1, 13):
        month_weather = weather_df[weather_df["month"] == month].copy()
        if month_weather.empty:
            continue

        # Predict indoor temperature for this month
        # We need to call predict_tin_7days but adapted for longer periods
        month_forecast = predict_tin_extended(
            weather_df=month_weather,
            schedules=schedules,
            indoor_seed=indoor_seed,
            building_age=building_age,
            building_type=building_type,
            floor_area=floor_area,
            climate_code=climate_code,
            tin_model=tin_model,
            schedule_priorities=schedule_priorities,
        )

        if month_forecast is None or month_forecast.empty:
            continue

        # Predict runtime using XGBoost predictor
        if runtime_predictor:
            month_runtime = estimate_runtime_with_predictor(
                month_forecast,
                runtime_predictor,
                hvac_mode=hvac_mode,
                use_ev=False,
            )
        else:
            month_runtime = estimate_runtime_simple(month_forecast)

        if month_runtime is not None and not month_runtime.empty:
            month_runtime["month"] = month
            all_predictions.append(month_runtime)

            # Compute monthly totals
            month_name = ["Jan", "Feb", "Mar", "Apr", "May", "Jun",
                         "Jul", "Aug", "Sep", "Oct", "Nov", "Dec"][month - 1]

            month_stats = {
                "total_runtime_hours": float(month_runtime["runtime_hours"].sum()),
                "avg_outdoor_temp": float(month_weather["outdoor_temp"].mean()),
            }

            # Add component breakdowns if available
            for comp in ["heat_sec_hours", "cool_sec_hours", "aux_sec_hours", "fan_sec_hours"]:
                if comp in month_runtime.columns:
                    month_stats[comp] = float(month_runtime[comp].sum())

            monthly_summary["months"][month_name] = month_stats

    if not all_predictions:
        return None, {"error": "No predictions generated"}

    # Combine all monthly predictions
    full_year_predictions = pd.concat(all_predictions, ignore_index=True)

    # Calculate annual totals
    monthly_summary["annual_runtime_hours"] = float(full_year_predictions["runtime_hours"].sum())
    monthly_summary["annual_kwh"] = monthly_summary["annual_runtime_hours"] * 3.5  # Default 3.5 kW

    return full_year_predictions, monthly_summary


def predict_tin_extended(
    weather_df: pd.DataFrame,
    schedules: Dict[str, Dict],
    indoor_seed: float,
    building_age: Optional[int],
    building_type: Optional[str],
    floor_area: Optional[float],
    climate_code: str,
    tin_model: Any,
    schedule_priorities: Optional[Dict[str, int]] = None,
) -> Optional[pd.DataFrame]:
    """
    Extended version of predict_tin_7days that handles arbitrary length weather data.
    Uses the same logic but processes longer time periods.
    """
    if weather_df is None or weather_df.empty or tin_model is None:
        return None

    # This is essentially the same as predict_tin_7days but without the 7-day limit
    # We'll call the existing function logic but adapted for the full dataset

    df = weather_df.copy()

    # Ensure time column exists
    if "time" not in df.columns:
        return None

    df["time"] = pd.to_datetime(df["time"])
    df = df.sort_values("time").reset_index(drop=True)

    # Add time features
    df["hour"] = df["time"].dt.hour
    df["month"] = df["time"].dt.month
    df["is_weekend"] = df["time"].dt.dayofweek.isin([5, 6]).astype(int)
    df["date"] = df["time"].dt.date

    # Cyclical encoding
    df["hour_sin"] = np.sin(2 * np.pi * df["hour"] / 24)
    df["hour_cos"] = np.cos(2 * np.pi * df["hour"] / 24)
    df["month_sin"] = np.sin(2 * np.pi * df["month"] / 12)
    df["month_cos"] = np.cos(2 * np.pi * df["month"] / 12)

    # Map schedules to each hour
    def get_schedule_for_time(ts: pd.Timestamp) -> Tuple[str, int, int]:
        name = _active_schedule_for_hour(ts, schedules, schedule_priorities)
        sched = schedules[name]
        return name, int(sched["heat_sp"]), int(sched["cool_sp"])

    schedule_info = df["time"].apply(get_schedule_for_time)
    df["schedule"] = [s[0] for s in schedule_info]
    df["heat_sp"] = [s[1] for s in schedule_info]
    df["cool_sp"] = [s[2] for s in schedule_info]
    df["deadband"] = df["cool_sp"] - df["heat_sp"]

    # Fill humidity if missing
    if "outdoor_humidity" not in df.columns or df["outdoor_humidity"].isna().all():
        df["outdoor_humidity"] = 50.0
    df["outdoor_humidity"] = df["outdoor_humidity"].fillna(50.0)

    # Building features
    df["building_age_yrs"] = building_age if building_age else 25
    df["floor_area_sqft"] = floor_area if floor_area else 1800

    # Climate zone dummies
    climate_cols = ["climate_3B", "climate_4B", "climate_3C", "climate_2B",
                    "climate_5B", "climate_4C", "climate_6B"]
    for c in climate_cols:
        df[c] = 1 if climate_code and c.split("_")[1] == climate_code else 0

    # Building type dummies
    bldg_cols = ["bldg_Townhouse", "bldg_Apartment", "bldg_Detached", "bldg_Other",
                 "bldg_Row House", "bldg_Semi-Detached", "bldg_Condominium",
                 "bldg_Multi-plex", "bldg_Loft"]
    for c in bldg_cols:
        df[c] = 1 if building_type and c.split("_", 1)[1] == building_type else 0

    # HVAC mode features
    df["hvac_heat"] = 0
    df["hvac_cool"] = 0
    df["hvac_auto"] = 1  # Default to auto
    df["hvac_off"] = 0

    # Effectively off features
    df["heat_effectively_off"] = (df["outdoor_temp"] > df["heat_sp"] + 5).astype(int)
    df["cool_effectively_off"] = (df["outdoor_temp"] < df["cool_sp"] - 5).astype(int)
    df["hvac_effectively_idle"] = (df["heat_effectively_off"] & df["cool_effectively_off"]).astype(int)

    # Initialize indoor temp prediction
    df["indoor_temp_pred"] = indoor_seed

    # Lag features - process sequentially for autoregressive prediction
    df["outdoor_temp_lag1"] = df["outdoor_temp"].shift(1).fillna(df["outdoor_temp"].iloc[0])
    df["indoor_temp_lag1"] = indoor_seed
    df["temp_diff"] = df["outdoor_temp"] - indoor_seed
    df["temp_diff_lag1"] = df["temp_diff"].shift(1).fillna(0)

    # Predict indoor temperature for each row
    # For efficiency, we'll predict in batches but maintain autoregressive nature
    predictions = []
    current_indoor = indoor_seed

    for idx in range(len(df)):
        row = df.iloc[idx:idx+1].copy()
        row["indoor_temp_lag1"] = current_indoor
        row["temp_diff"] = row["outdoor_temp"].values[0] - current_indoor
        row["temp_diff_lag1"] = df.iloc[max(0, idx-1)]["temp_diff"] if idx > 0 else 0

        # Prepare features in correct order (matching TIN_FEATURES)
        features = row[TIN_FEATURES].values

        try:
            if hasattr(tin_model, "predict"):
                pred = float(tin_model.predict(features)[0])
            else:
                pred = current_indoor  # Fallback
        except Exception:
            pred = current_indoor

        # Clamp to reasonable range
        pred = max(55, min(95, pred))
        predictions.append(pred)
        current_indoor = pred

    df["indoor_temp_pred"] = predictions

    return df


