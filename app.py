def find_nearest_outdoor_location(lat: float, lon: float) -> Tuple[Optional[int], float]:
    """
    Find the nearest location_id from the outdoor temps dataset based on lat/lon.
    Returns (location_id, distance_km).
    """
    locations = load_outdoor_locations()
    if locations is None or locations.empty:
        return None, float("inf")

    # Calculate haversine distance to all locations
    R = 6371.0
    lat1, lon1 = np.radians(lat), np.radians(lon)
    lat2 = np.radians(locations["lat"].values)
    lon2 = np.radians(locations["lon"].values)
    dlat = lat2 - lat1
    dlon = lon2 - lon1
    a = np.sin(dlat / 2) ** 2 + np.cos(lat1) * np.cos(lat2) * np.sin(dlon / 2) ** 2
    distances = R * 2 * np.arctan2(np.sqrt(a), np.sqrt(1 - a))

    min_idx = int(np.argmin(distances))
    nearest_loc_id = int(locations.iloc[min_idx]["location_id"])
    nearest_dist = float(distances[min_idx])

    return nearest_loc_id, nearest_dist


@st.cache_data(show_spinner=False)
def load_outdoor_temps_for_location(location_id: int, year: int) -> Optional[pd.DataFrame]:
    """
    Load hourly outdoor temperature data for a specific location and year.

    Data structure: OUTDOOR_TEMPS_DIR / location_id=XXXX / year=YYYY.parquet
    Returns DataFrame with columns: datetime_utc, tout_c, rh_pct
    """
    if not OUTDOOR_TEMPS_DIR.exists():
        return None

    # Format location_id with leading zeros (4 digits)
    loc_folder = OUTDOOR_TEMPS_DIR / f"location_id={location_id:04d}"
    if not loc_folder.exists():
        # Try without leading zeros
        loc_folder = OUTDOOR_TEMPS_DIR / f"location_id={location_id}"

    if not loc_folder.exists():
        return None

    parquet_file = loc_folder / f"year={year}.parquet"
    if not parquet_file.exists():
        return None

    try:
        df = pd.read_parquet(parquet_file)
        # Convert Celsius to Fahrenheit for consistency with the app
        if "tout_c" in df.columns:
            df["outdoor_temp"] = df["tout_c"] * 9/5 + 32
        if "rh_pct" in df.columns:
            df["outdoor_humidity"] = df["rh_pct"]
        if "datetime_utc" in df.columns:
            df["time"] = pd.to_datetime(df["datetime_utc"])
        return df
    except Exception as e:
        print(f"Error loading outdoor temps for location {location_id}, year {year}: {e}")
        return None


def available_years_for_location(location_id: int) -> List[int]:
    loc_folder = OUTDOOR_TEMPS_DIR / f"location_id={location_id:04d}"
    if not loc_folder.exists():
        loc_folder = OUTDOOR_TEMPS_DIR / f"location_id={location_id}"
    if not loc_folder.exists():
        return []
    years: List[int] = []
    for path in loc_folder.glob("year=*.parquet"):
        stem = path.stem
        try:
            years.append(int(stem.split("=", 1)[1]))
        except (IndexError, ValueError):
            continue
    return sorted(set(years))


def load_full_year_outdoor_temps(lat: float, lon: float, year: int = 2023) -> Tuple[Optional[pd.DataFrame], Optional[int], float]:
    """
    Load a full year of hourly outdoor temperature data for the nearest location.

    Returns: (weather_df, location_id, distance_km)

    The weather_df contains hourly data with columns:
    - time: datetime
    - outdoor_temp: temperature in Fahrenheit
    - outdoor_humidity: relative humidity %
    """
    # Find nearest location
    location_id, distance_km = find_nearest_outdoor_location(lat, lon)
    if location_id is None:
        return None, None, float("inf")

    # Load the year's data
    df = load_outdoor_temps_for_location(location_id, year)
    if df is None:
        return None, location_id, distance_km

    # Ensure we have the required columns
    required_cols = ["time", "outdoor_temp"]
    if not all(c in df.columns for c in required_cols):
        return None, location_id, distance_km

    # Sort by time and reset index
    df = df.sort_values("time").reset_index(drop=True)

    return df, location_id, distance_km


