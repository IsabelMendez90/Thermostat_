def parse_action_from_text(text: str) -> Tuple[Optional[Dict[str, Any]], str]:
    # Try parsing with <ACTION> tags first
    m = re.search(r"<ACTION>(.*?)</ACTION>", text, re.DOTALL)
    if m:
        try:
            action_json = json.loads(m.group(1))
            cleaned = re.sub(r"<ACTION>.*?</ACTION>", "", text, flags=re.DOTALL).strip()
            return action_json, cleaned
        except json.JSONDecodeError:
            pass

    # Fallback: Try to find JSON with "type":"create_scenario" anywhere in the text
    # Look for {...} pattern that contains create_scenario
    json_pattern = r'\{[^{}]*"type"\s*:\s*"create_scenario"[^{}]*(?:\{[^{}]*\}[^{}]*)*\}'
    matches = re.finditer(json_pattern, text, re.DOTALL)

    for match in matches:
        try:
            # Try to parse the matched JSON
            json_str = match.group(0)
            # Handle nested braces by counting them
            brace_count = 1
            start_pos = match.start() + 1
            end_pos = start_pos

            while brace_count > 0 and end_pos < len(text):
                if text[end_pos] == '{':
                    brace_count += 1
                elif text[end_pos] == '}':
                    brace_count -= 1
                end_pos += 1

            json_str = text[match.start():end_pos]
            action_json = json.loads(json_str)

            # Remove the JSON from the explanation
            cleaned = text[:match.start()] + text[end_pos:]
            cleaned = cleaned.strip()
            return action_json, cleaned
        except (json.JSONDecodeError, ValueError):
            continue

    return None, text

def resolve_schedule_key(name: str) -> Optional[str]:
    if not name:
        return None
    if name in st.session_state.schedules:
        return name
    lower_map = {k.lower(): k for k in st.session_state.schedules.keys()}
    if name.lower() in lower_map:
        return lower_map[name.lower()]
    choices = list(st.session_state.schedules.keys())
    hits = fuzzy_match(name, choices, threshold=75)
    if hits:
        return hits[0][0]
    return None

